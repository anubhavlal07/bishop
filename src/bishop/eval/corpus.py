"""Loading the labelled corpus.

The golden set is 20 hand-labelled alerts in `fixtures/alerts/`, generated by
`scripts/build_corpus.py`. Each carries a `labels` block with the expected
verdict, the techniques it should surface, and a `why` sentence justifying the
label — because a golden set whose labels cannot be argued with is a golden set
nobody checked.

`labels` is stripped from the `Alert` handed to the graph. Bishop must never
see ground truth during a run; a scorecard produced by a system that could read
the answer is worth nothing.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from bishop.schema import Alert

CORPUS_DIR = Path(__file__).resolve().parents[3] / "fixtures" / "alerts"

#: The held-out set. Written after the fusion thresholds were fixed, run
#: separately, and never used to tune anything — see `scripts/build_holdout.py`
#: for the protocol it is kept under. It is a separate directory rather than a
#: flag on the golden set so that `load_corpus()` cannot pick it up by accident.
HOLDOUT_DIR = Path(__file__).resolve().parents[3] / "fixtures" / "holdout"


@dataclass(frozen=True, slots=True)
class LabelledAlert:
    alert: Alert
    expected_verdict: str
    expected_techniques: tuple[str, ...]
    should_escalate: bool
    why: str
    synthetic: bool

    @property
    def alert_id(self) -> str:
        return self.alert.alert_id

    @property
    def is_injection_case(self) -> bool:
        return self.alert_id.startswith("INJ-")


def load_corpus(directory: Path | None = None) -> list[LabelledAlert]:
    """Load every labelled alert, sorted by id so runs are comparable."""
    source = directory or CORPUS_DIR
    if not source.exists():
        raise FileNotFoundError(f"no corpus at {source}. Run `just corpus` to generate it.")

    loaded: list[LabelledAlert] = []
    for path in sorted(source.glob("*.json")):
        payload: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
        labels = payload.pop("labels", {})
        # The alert handed to the graph carries no ground truth.
        alert = Alert.model_validate(payload)
        loaded.append(
            LabelledAlert(
                alert=alert,
                expected_verdict=str(labels.get("verdict", "")),
                expected_techniques=tuple(labels.get("techniques") or []),
                should_escalate=bool(labels.get("should_escalate")),
                why=str(labels.get("why", "")),
                synthetic=bool(labels.get("synthetic", True)),
            )
        )
    return loaded


def corpus_techniques(directory: Path | None = None) -> dict[str, list[str]]:
    """Alert id → expected techniques. Feeds the coverage matrix."""
    return {item.alert_id: list(item.expected_techniques) for item in load_corpus(directory)}


def distribution(corpus: list[LabelledAlert]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for item in corpus:
        counts[item.expected_verdict] = counts.get(item.expected_verdict, 0) + 1
    return dict(sorted(counts.items()))
